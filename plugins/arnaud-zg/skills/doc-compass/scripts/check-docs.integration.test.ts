import { spawnSync } from "node:child_process";
import { cpSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { afterEach, describe, expect, test } from "vitest";

// The check as a person runs it: `node check-docs.mjs` in a real folder, read from its exit code
// and what it prints. Every project here is written to a temporary folder; nothing is mocked.

const CHECK = path.join(import.meta.dirname, "check-docs.mjs");
const TEMPLATES = path.join(import.meta.dirname, "..", "templates");

let project: string | undefined;

afterEach(() => {
  if (project) rmSync(project, { recursive: true, force: true });
  project = undefined;
});

function projectWith(files: Record<string, string>) {
  project = mkdtempSync(path.join(os.tmpdir(), "doc-compass-check-"));
  for (const [relative, text] of Object.entries(files)) {
    mkdirSync(path.dirname(path.join(project, relative)), { recursive: true });
    writeFileSync(path.join(project, relative), text);
  }
  return project;
}

function check(cwd: string, ...args: string[]) {
  const { status, stdout, stderr } = spawnSync(process.execPath, [CHECK, ...args], {
    cwd,
    encoding: "utf8",
    env: { NO_COLOR: "", FORCE_COLOR: "" },
  });
  return { status, stdout, stderr };
}

const home = (title: string) => `# ${title}\n\n[🏠 Home](README.md) · **${title}**\n`;

describe("given a docs folder that holds", () => {
  test("when the check runs with no path, then it reads docs/, says so and exits 0", () => {
    const cwd = projectWith({
      "docs/README.md": "# Docs\n\n[Tutorial](tutorial.md)\n",
      "docs/tutorial.md": home("Tutorial"),
    });
    const { status, stdout } = check(cwd);
    expect(stdout).toContain("✓ 2 pages in docs hold.");
    expect(status).toBe(0);
  });

  test("when the templates are copied as they ship, then they hold too", () => {
    const cwd = projectWith({});
    cpSync(TEMPLATES, path.join(cwd, "docs"), { recursive: true });
    const { status, stdout } = check(cwd);
    expect(stdout).toContain("hold.");
    expect(status).toBe(0);
  });
});

describe("given a docs folder with breaks", () => {
  test("when the check runs, then each break is printed with its file, line and fix, and it exits 1", () => {
    const cwd = projectWith({
      "docs/README.md": "# Docs\n\n[How-to](how-to.md)\n",
      "docs/how-to.md": `${home("How-to")}\n[Install](#install-it)\n`,
      "docs/lost.md": home("Lost"),
    });
    const { status, stdout } = check(cwd);
    expect(stdout).toContain("docs/lost.md:1  indexed");
    expect(stdout).toContain("docs/how-to.md:5  resolves");
    expect(stdout).toContain("→ point at where it lives now, or remove the link");
    expect(stdout).toContain("✗ 2 findings in 2 of 3 pages.");
    expect(status).toBe(1);
  });

  test("when --json is given, then the findings are printed as JSON", () => {
    const cwd = projectWith({ "docs/README.md": "# Docs\n", "docs/lost.md": home("Lost") });
    const { status, stdout } = check(cwd, "--json");
    const report = JSON.parse(stdout) as {
      sets: { docs: string; pages: number }[];
      findings: { rule: string; path: string }[];
    };
    expect(report.sets).toEqual([{ docs: "docs", pages: 2 }]);
    expect(report.findings.map(({ rule, path: where }) => [rule, where])).toEqual([
      ["indexed", "docs/lost.md"],
    ]);
    expect(status).toBe(1);
  });

  test("when --ban is given, then the banned string is reported", () => {
    const cwd = projectWith({ "docs/README.md": "# Docs — home\n" });
    expect(check(cwd).status).toBe(0);
    const { status, stdout } = check(cwd, "--ban", "—");
    expect(stdout).toContain("docs/README.md:1  banned");
    expect(status).toBe(1);
  });

  test("when a generated page names a source that is gone, then it is reported from the project root", () => {
    const cwd = projectWith({
      "docs/README.md": "# Docs\n\n[Flow](flow.md)\n",
      "docs/flow.md": `${home("Flow")}\n> Generated by \`pnpm flow\` from \`packages/engine\`.\n`,
    });
    expect(check(cwd).stdout).toContain("docs/flow.md:5  generated");
    mkdirSync(path.join(cwd, "packages/engine"), { recursive: true });
    expect(check(cwd).status).toBe(0);
  });
});

describe("given an index above the docs folder", () => {
  test("when --index points at it, then links resolve from its folder", () => {
    const cwd = projectWith({
      "README.md": "# Kit\n\n[Tutorial](docs/tutorial.md)\n",
      "docs/tutorial.md": "# Tutorial\n\n[Home](../README.md) · [Gone](how-to.md)\n",
    });
    const { status, stdout } = check(cwd, "docs", "--index", "../README.md");
    expect(stdout).toContain("docs/tutorial.md:3  resolves");
    expect(stdout).not.toContain("  framed\n");
    expect(status).toBe(1);
  });
});

describe("given a doc-compass.json", () => {
  const config = (value: unknown) => JSON.stringify(value);

  test("when the check runs with no folder, then it checks every listed set with the bans", () => {
    const cwd = projectWith({
      "doc-compass.json": config({
        ban: ["—"],
        docs: ["docs", { folder: "tool/docs", index: "../README.md" }],
      }),
      "docs/README.md": "# Docs\n",
      "README.md": "# Repo\n",
      "tool/README.md": "# Tool — home\n\n[Guide](docs/guide.md)\n",
      "tool/docs/guide.md": "# Guide\n\n[Tool](../README.md)\n",
    });
    const { status, stdout } = check(cwd);
    expect(stdout).toContain("✓ 1 page in docs holds.");
    expect(stdout).toContain("tool/README.md:1  banned");
    expect(status).toBe(1);
  });

  test("when a folder is named, then only it is checked, and the config's bans still apply", () => {
    const cwd = projectWith({
      "doc-compass.json": config({ ban: ["—"], docs: ["docs", "gone"] }),
      "docs/README.md": "# Docs — home\n",
    });
    const { status, stdout } = check(cwd, "docs");
    expect(stdout).toContain("docs/README.md:1  banned");
    expect(status).toBe(1);
  });

  test.each([
    [{ docs: ["docs"], bann: [] }, "unknown key bann"],
    [{ docs: [] }, '"docs" must list at least one folder'],
    [{ docs: [{ folder: "docs", idx: "x" }] }, 'each "docs" entry is a folder'],
    [{ docs: ["docs"], ban: [""] }, '"ban" must be a list of non-empty strings'],
  ])("when it says %j, then it says what is wrong and exits 2", (value, message) => {
    const cwd = projectWith({ "doc-compass.json": config(value), "docs/README.md": "# Docs\n" });
    const { status, stderr } = check(cwd);
    expect(stderr).toContain(message);
    expect(status).toBe(2);
  });

  test("when it is not JSON, then it says so and exits 2", () => {
    const cwd = projectWith({ "doc-compass.json": "{ docs: [", "docs/README.md": "# Docs\n" });
    const { status, stderr } = check(cwd);
    expect(stderr).toContain("doc-compass.json is not valid JSON");
    expect(status).toBe(2);
  });
});

describe("given a link whose case differs from the file on disk", () => {
  test("when the check runs, then it is reported on every system, case-insensitive disks too", () => {
    const cwd = projectWith({
      "CONTRIBUTING.md": "# Contributing\n",
      "docs/README.md": "# Docs\n\n[Contributing](../contributing.md)\n",
    });
    const { status, stdout } = check(cwd);
    expect(stdout).toContain("docs/README.md:3  resolves");
    expect(status).toBe(1);
  });
});

describe("given nothing to check", () => {
  test("when the folder is missing, then it says so and exits 2", () => {
    const { status, stderr } = check(projectWith({ "a.txt": "" }), "nowhere");
    expect(stderr).toContain("nowhere is not a folder.");
    expect(status).toBe(2);
  });

  test("when the folder holds no page, then it says so and exits 2", () => {
    const { status, stderr } = check(projectWith({ "docs/a.txt": "" }));
    expect(stderr).toContain("docs holds no Markdown page.");
    expect(status).toBe(2);
  });

  test("when --index is given without a folder, then it says so and exits 2", () => {
    const { status, stderr } = check(
      projectWith({ "docs/README.md": "# Docs\n" }),
      "--index",
      "x.md",
    );
    expect(stderr).toContain("--index needs a <folder>.");
    expect(status).toBe(2);
  });

  test("when an option is unknown, then it prints the usage and exits 2", () => {
    const { status, stderr } = check(projectWith({ "docs/README.md": "# Docs\n" }), "--nope");
    expect(stderr).toContain("Usage: node check-docs.mjs");
    expect(status).toBe(2);
  });
});
